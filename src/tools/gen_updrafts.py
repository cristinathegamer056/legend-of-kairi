#!/usr/bin/env python3
"""Regenerate runtime/sora_updraft_data.inc: BotW's updraft columns (actors AscendingCurrent*) of the main map, for Sora's
KH2 glide (runtime/sora.c, updraft). BotW lifts only the paraglider in them; Sora's glide is the mod's own, so it needs
the columns itself.

Read from YOUR game files (no network): the map units romfs/Map/MainField/*/*.smubin and the DLC's
aoc/Map/AocField/*/*.smubin (same world coordinates), and each variant's AIProgram (Actor/Pack/<name>.sbactorpack,
action AscendingCurrent, SInst WindSpeed).

The column (BotW 1.9.0 AscendingCurrent, 0x71005f0d80 / 0x71005f1614 / 0x71005f0f60): a box of size 2 * Scale along the
actor's axes, standing on Translate (center = Translate + up * Scale.y), pushing along the actor's up axis at
WindSpeed * 30 (the wind area's speed; the Chemical_Updraft element has the same size). Rotate is one float (about y) or
three (x, y, z; R = Rz * Ry * Rx, GUESS: sead's order).

  python -I tools/gen_updrafts.py --romfs <romfs dir> [--aoc <aoc dir>] [--out runtime/sora_updraft_data.inc]
Needs oead (pip install oead; the kit's python has it).
"""
import argparse
import glob
import math
import os

import oead


def vec(v, n=3):
    if isinstance(v, (int, float)) or hasattr(v, 'v'):
        f = float(v.v if hasattr(v, 'v') else v)
        return [f] * n
    return [float(x.v if hasattr(x, 'v') else x) for x in v]


def rot_matrix(r):
    """rows of R (world = R * local); r = [rx, ry, rz] radians, R = Rz * Ry * Rx"""
    cx, sx, cy, sy, cz, sz = math.cos(r[0]), math.sin(r[0]), math.cos(r[1]), math.sin(r[1]), math.cos(r[2]), math.sin(r[2])
    return [[cz * cy, cz * sy * sx - sz * cx, cz * sy * cx + sz * sx],
            [sz * cy, sz * sy * sx + cz * cx, sz * sy * cx - cz * sx],
            [-sy, cy * sx, cy * cx]]


def wind_speed(name, packdirs, cache={}):
    if name in cache:
        return cache[name]
    sp = None
    for d in packdirs:
        p = os.path.join(d, name + '.sbactorpack')
        if not os.path.isfile(p):
            continue
        sarc = oead.Sarc(oead.yaz0.decompress(open(p, 'rb').read()))
        for f in sarc.get_files():
            if not f.name.endswith('.baiprog'):
                continue
            pio = oead.aamp.ParameterIO.from_binary(bytes(f.data))
            for _, lst in pio.lists['Action'].lists.items():
                df = lst.objects['Def']
                if str(df.params['ClassName'].v) == 'AscendingCurrent' and 'SInst' in lst.objects:
                    sp = float(lst.objects['SInst'].params['WindSpeed'].v)
        if sp is not None:
            break
    cache[name] = sp
    return sp


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--romfs', required=True)
    ap.add_argument('--aoc')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'runtime', 'sora_updraft_data.inc'))
    a = ap.parse_args()
    units = sorted(glob.glob(os.path.join(a.romfs, 'Map', 'MainField', '*', '*.smubin')))
    if a.aoc:
        units += sorted(glob.glob(os.path.join(a.aoc, 'Map', 'AocField', '*', '*.smubin')))
    packdirs = [os.path.join(a.romfs, 'Actor', 'Pack')] + ([os.path.join(a.aoc, 'Actor', 'Pack')] if a.aoc else [])
    rows, seen = [], set()
    for u in units:
        d = oead.byml.from_binary(oead.yaz0.decompress(open(u, 'rb').read()))
        for o in d.get('Objs', []):
            n = str(o.get('UnitConfigName', ''))
            if not n.startswith('AscendingCurrent'):
                continue
            t = vec(o['Translate'])
            r = o.get('Rotate', 0.0)
            r = [0.0, float(r.v if hasattr(r, 'v') else r), 0.0] if not isinstance(r, (list, oead.byml.Array)) else vec(r)
            s = vec(o.get('Scale', 1.0))
            key = (n, round(t[0], 2), round(t[1], 2), round(t[2], 2))
            if key in seen:
                continue
            seen.add(key)
            ws = wind_speed(n, packdirs)
            if ws is None:
                print('skip %s (no WindSpeed found)' % n)
                continue
            rows.append((n, os.path.basename(u), t, rot_matrix(r), s, ws * 30.0))
    rows.sort(key=lambda x: (x[2][0], x[2][2]))
    out = ['// Generated by tools/gen_updrafts.py from the game files - do not edit. BotW updraft columns (AscendingCurrent*) of',
           '// the main map: {pos x y z, R rows (world = R * local), half size x y z (= map Scale), push u/s (WindSpeed * 30)}.',
           '// The box stands on pos: local y in [0, 2 * half y], |local x| <= half x, |local z| <= half z; the push is along R\'s y axis.',
           '// %d columns.' % len(rows)]
    for n, unit, t, R, s, sp in rows:
        f = lambda v: '%.4ff' % v
        out.append('{{%s, %s, %s}, {%s}, {%s, %s, %s}, %s},  // %s (%s)' % (
            f(t[0]), f(t[1]), f(t[2]), ', '.join(f(x) for row in R for x in row), f(s[0]), f(s[1]), f(s[2]), f(sp), n, unit))
    with open(a.out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    print('%s: %d columns' % (a.out, len(rows)))


if __name__ == '__main__':
    main()
