#!/usr/bin/env python3
"""s247 kbspan: writes runtime/sora_kbspan.h's table = each KH2 Keyblade's own TIP length (cm along its grip bone) from the
player's KH2 extract.

  python -I tools/kbspan_gen.py --kh2 D:/KH2Extract [--out runtime/sora_kbspan.h] [--check]

Source (KH2 data): obj/W_EX010[_<set>].mdlx, BAR entry type 23 (the model's collision table: u32 count, rows from +0x40, 20 bytes
each: u8 group, u8, s16, u8 type, u8 shape, s16 bone, s16 x, y, z, ...). The row of TYPE 15 on bone 2 (the grip bone) is KH2's
tip marker: x = -<tip cm> (the blade runs along bone 2's -x; Kingdom Key -78, Oblivion -103, Ultima Weapon / Fenrir -130). Every
model has exactly one. Which Keyblade id has which set: KBFX_TAB in runtime/sora_kbfx.h (read here, not repeated); rows without a
W_EX010 set of their own ("s1" ... our Keyblades) get no row = the runtime keeps today's ribbon.
--check: exit 1 when the header on disk differs from what the extract gives (nothing written).
Numbers only (ids + cm) go into the header: no KH2 bytes.
"""
import argparse
import os
import re
import struct
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PKG_ORDER = ["kh2_first", "kh2_second", "kh2_third", "kh2_fourth", "kh2_fifth", "kh2_sixth"]
GRIP_BONE = 2
TIP_TYPE = 15


def die(m):
    raise SystemExit("[kbspan_gen] " + m)


def kh2_obj(kh2, name):
    hit = None
    for p in PKG_ORDER:
        c = os.path.join(kh2, p, "original", "obj", name)
        if os.path.isfile(c):
            hit = c
    return hit


def tip_cm(path):
    d = open(path, "rb").read()
    if d[:4] != b"BAR\x01":
        die("%s is not a BAR file" % path)
    tips = []
    for i in range(struct.unpack_from("<I", d, 4)[0]):
        t, _, _, off, sz = struct.unpack_from("<HH4sII", d, 16 + 16 * i)
        if t != 23:
            continue
        n = struct.unpack_from("<i", d, off)[0]
        if not 0 < n < 256 or 0x40 + 20 * n > sz:
            die("%s: odd collision table (%d rows)" % (path, n))
        for k in range(n):
            _, _, _, ty, _, bone, x, y, z = struct.unpack_from("<BBhBBhhhh", d, off + 0x40 + 20 * k)
            if ty == TIP_TYPE:
                if bone != GRIP_BONE or y or z or x >= 0:
                    die("%s: the tip marker is not on bone 2's -x (bone %d, %d %d %d)" % (path, bone, x, y, z))
                tips.append(-x)
    if len(tips) != 1:
        die("%s: %d tip markers (want 1)" % (path, len(tips)))
    return tips[0]


def kbfx_rows():
    src = open(os.path.join(ROOT, "runtime", "sora_kbfx.h"), encoding="utf-8").read()
    body = src[src.index("KBFX_TAB[] = {"):]
    body = body[:body.index("};")]
    rows = re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*"([0-9a-z]*)"\s*,\s*"((?:[^"\\]|\\.)*)"', body)
    if len(rows) < 30:
        die("could not read KBFX_TAB from runtime/sora_kbfx.h (%d rows)" % len(rows))
    return [(int(i, 16), s, n) for i, s, n in rows]


def table(kh2):
    out = []
    for item, st, name in kbfx_rows():
        if st and st[1] != "0":
            continue  # (our own Keyblades: no KH2 model)
        mdl = "W_EX010%s.mdlx" % ("_" + st.upper() if st else "")
        p = kh2_obj(kh2, mdl)
        if not p:
            die("no obj/%s in the KH2 extract %s" % (mdl, kh2))
        out.append((item, st, name, tip_cm(p)))
    return out


def header(rows):
    lines = [
        "// sora_kbspan.h (s247 kbspan): each KH2 Keyblade's swing ribbon reaches ITS OWN tip. GENERATED by tools/kbspan_gen.py from",
        "// the KH2 extract (do not edit by hand: re-run it). Notes: recon/s247/S247_HELPER_KBSE.md section 8.",
        "//",
        "// KH2 data: every Keyblade model obj/W_EX010_<set>.mdlx has one collision row of type 15 on bone 2 (the grip bone) = its tip",
        "// marker, cm along the blade. The blade bakes (sorabake HitBake) end the segment at the bake Keyblade's farthest vertex: the",
        "// main hand = the Kingdom Key (78 cm), the LEFT hand of Valor / Master / Final = Star Seeker (bakes.py form_env left =",
        "// W_EX010_30: 103.64 cm, measured in every installed *_hits_l*.bin in s249), so with kbspan 0 every ribbon ends there. With",
        "// live \"set kbspan 1\" kbspan_seg moves the ribbon's FAR end along the baked grip -> tip direction to tip_cm / the hand's baked",
        "// length (the near end stays: element 10's own span numbers have no settled unit). Only the ribbon: hit detection, wpn_reach,",
        "// the beam, sparks and the shed bits keep the baked segment.",
        "// Today's ribbon (factor 1) for: kbspan 0, our own Keyblades (no row), an id without a row, Mickey, kbfx 0, a BotW weapon.",
        "// Needs (sora.c, after sora_kbfx.h): kbfx_item, kbfx_row, KBFX_TAB, g_kbfx, IN_MICKEY, LOG.",
        "#pragma once",
        "",
        "#define KBSPAN_BAKED_CM 78.0f  // the Kingdom Key's tip: where the MAIN hand's baked segment ends (its own marker says 78 too)",
        "#define KBSPAN_BAKED_L_CM 103.64f  // the LEFT hand's baked segment (Valor / Master / Final): Star Seeker W_EX010_30's farthest",
        "                                   // vertex; data/forms/{valor,master,final}_hits_l*.bin = 103.64 cm in every frame (s249)",
        "typedef struct { uint16_t id; uint8_t tip_cm; } KbspanRow;  // KH2 item id -> the model's tip marker, cm",
        "static const KbspanRow KBSPAN_TAB[] = {",
    ]
    for item, st, name, cm in rows:
        lines.append("    {0x%03x, %3d},  // %s (W_EX010%s)" % (item, cm, name, "_" + st.upper() if st else ""))
    lines += [
        "};",
        "#define KBSPAN_N ((int)(sizeof KBSPAN_TAB / sizeof KBSPAN_TAB[0]))",
        "",
        "static int g_kbspan = 1;  // live \"set kbspan\": 1 = each KH2 Keyblade's ribbon reaches its own tip (s249: default ON, the user verified it; 0 = 78 cm for all)",
        "static uint8_t g_kbspan_used[KBSPAN_N];  // its first use was logged",
        "",
        "static int kbspan_row(int id) {",
        "    for (int i = 0; i < KBSPAN_N; i++)",
        "        if (KBSPAN_TAB[i].id == id) return i;",
        "    return -1;",
        "}",
        "// the baked segment length of blade `blade` (0 main: the Kingdom Key bake, 1 = the left hand's Star Seeker bake), cm",
        "static float kbspan_baked(int blade) { return blade == 1 ? KBSPAN_BAKED_L_CM : KBSPAN_BAKED_CM; }",
        "// the far-end factor for Keyblade `id` in blade `blade` (1 = today's ribbon for an id without a row)",
        "static float kbspan_factor_b(int id, int blade) {",
        "    int r = kbspan_row(id);",
        "    return r < 0 ? 1.0f : (float)KBSPAN_TAB[r].tip_cm / kbspan_baked(blade);",
        "}",
        "static float kbspan_factor(int id) { return kbspan_factor_b(id, 0); }  // (the main hand)",
        "// The ribbon segment of blade `blade` (0 main, 1 = Valor's left / Master's / Final's 2nd): seg = the baked world segment",
        "// (grip xyz, tip xyz, from blade_world) -> out = grip unchanged, tip = grip + (tip - grip) * factor. botw = blade 0 holds a",
        "// BotW weapon (its own reach, wpn_reach): untouched. Returns the factor used.",
        "static float kbspan_seg(int blade, const float seg[6], bool botw, float out[6]) {",
        "    for (int k = 0; k < 6; k++) out[k] = seg[k];",
        "    if (!g_kbspan || !g_kbfx || IN_MICKEY || botw || blade < 0 || blade > 1) return 1.0f;",
        "    int id = kbfx_item(blade), r = kbspan_row(id);",
        "    if (r < 0) return 1.0f;",
        "    float f = kbspan_factor_b(id, blade);",
        "    for (int k = 0; k < 3; k++) out[3 + k] = seg[k] + (seg[3 + k] - seg[k]) * f;",
        "    if (!g_kbspan_used[r]) {",
        "        g_kbspan_used[r] = 1;",
        "        int fr = kbfx_row(id);",
        "        LOG(\"[sora] kbspan: %s (0x%x, blade %d) ribbon reaches its own tip: %d cm (x%.3f of the baked %.2f cm)\\n\",",
        "            fr >= 0 ? KBFX_TAB[fr].name : \"?\", id, blade, KBSPAN_TAB[r].tip_cm, f, kbspan_baked(blade));",
        "    }",
        "    return f;",
        "}",
        "// once per frame (after kbfx_tick): one line when the key changes",
        "static void kbspan_tick(void) {",
        "    static int last = -1;",
        "    if (g_kbspan == last) return;",
        "    if (last >= 0 || g_kbspan)",
        "        LOG(g_kbspan ? \"[sora] kbspan 1: each KH2 Keyblade's swing ribbon reaches its own tip (KH2's tip marker)\\n\"",
        "                     : \"[sora] kbspan 0: every ribbon ends at the baked blade (78 cm; left hand 103.6)\\n\");",
        "    last = g_kbspan;",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kh2", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "runtime", "sora_kbspan.h"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = table(a.kh2)
    h = header(rows)
    for item, st, name, cm in rows:
        print("  0x%03x %-22s %3d cm" % (item, name, cm))
    if a.check:
        old = open(a.out, encoding="utf-8").read() if os.path.isfile(a.out) else ""
        print("kbspan_gen: %s is %s" % (a.out, "up to date" if old == h else "DIFFERENT"))
        sys.exit(0 if old == h else 1)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(h)
    print("kbspan_gen: %d rows -> %s" % (len(rows), a.out))


if __name__ == "__main__":
    main()
